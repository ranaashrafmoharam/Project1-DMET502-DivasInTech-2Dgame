import os
from PIL import Image

output_file = 'src/core/EmbeddedSprites.h'

sprites = [
    'kai', 'zane', 'cole', 'jay', 'wu', 'garmadon',
    'venomari', 'hypnobrai', 'constrictai',
    'shard', 'sword', 'shuriken', 'acid', 'sonic',
    'monastery_gate', 'cherry_tree', 'stone_lantern',
    'training_dummy', 'prayer_gong', 'dragon_banner'
]

with open(output_file, 'w', encoding='utf-8') as f:
    f.write('// Autogenerated embedded sprite textures for pixel art rendering\n')
    f.write('#pragma once\n\n')
    f.write('struct SpriteRaw {\n')
    f.write('    const char* name;\n')
    f.write('    int width;\n')
    f.write('    int height;\n')
    f.write('    const unsigned char* pixels;\n')
    f.write('};\n\n')
    
    for s_name in sprites:
        path = f'assets/sprites/{s_name}.png'
        if not os.path.exists(path):
            print(f'Warning: {path} not found!')
            continue
        im = Image.open(path).convert('RGBA')
        w, h = im.size
        data = list(im.tobytes())
        f.write(f'// Sprite: {s_name} ({w}x{h})\n')
        f.write(f'static const unsigned char SPRITE_DATA_{s_name}[] = {{\n')
        for i in range(0, len(data), 16):
            chunk = data[i:i+16]
            f.write('    ' + ', '.join(f'0x{b:02x}' for b in chunk) + ',\n')
        f.write('};\n\n')
        
    f.write('static const SpriteRaw ALL_EMBEDDED_SPRITES[] = {\n')
    for s_name in sprites:
        path = f'assets/sprites/{s_name}.png'
        if os.path.exists(path):
            im = Image.open(path)
            w, h = im.size
            f.write(f'    {{"{s_name}", {w}, {h}, SPRITE_DATA_{s_name}}},\n')
    f.write('    {nullptr, 0, 0, nullptr}\n')
    f.write('};\n')

print('EmbeddedSprites.h created successfully!')

