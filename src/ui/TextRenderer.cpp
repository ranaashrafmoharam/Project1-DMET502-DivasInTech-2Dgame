static const unsigned char* findGlyph(char c) {
    char upper = (char)std::toupper((unsigned char)c);
    for (const auto& g : BITMAP_FONT) {
        if (g.c == upper) return g.rows;
    }
    return BITMAP_FONT[0].rows; // fallback space
}

void TextRenderer::drawText(const std::string& text, float x, float y, float scale, const glm::vec4& color) {
    Renderer& ren = Renderer::instance();
    float cursorX = x;
    const float pixelSize = scale;
    const float charAdvance = 8.0f * pixelSize;

    for (char c : text) {
        if (c == '\n') {
            y -= 10.0f * pixelSize;
            cursorX = x;
            continue;
        }

        const unsigned char* rows = findGlyph(c);
        for (int r = 0; r < 8; ++r) {
            unsigned char rowByte = rows[r];
            // Invert row index so r=0 is top of character
            float py = y + (7 - r) * pixelSize;
            for (int bit = 0; bit < 8; ++bit) {
                if (rowByte & (0x80 >> bit)) {
                    float px = cursorX + bit * pixelSize;
                    ren.drawRect(px, py, pixelSize, pixelSize, color);
                }
            }
        }
        cursorX += charAdvance;
    }
}

void TextRenderer::drawTextCentered(const std::string& text, float cx, float y, float scale, const glm::vec4& color) {
    float w = getTextWidth(text, scale);
    drawText(text, cx - w * 0.5f, y, scale, color);
}

void TextRenderer::drawTextWithShadow(const std::string& text, float x, float y, float scale, 
                                      const glm::vec4& color, const glm::vec4& shadowColor) {
    // 1-pixel shadow offset in font scale
    float offset = scale * 0.8f;
    drawText(text, x + offset, y - offset, scale, shadowColor);
    drawText(text, x, y, scale, color);
}

void TextRenderer::drawTextCenteredWithShadow(const std::string& text, float cx, float y, float scale, 
                                              const glm::vec4& color, const glm::vec4& shadowColor) {
    float w = getTextWidth(text, scale);
    drawTextWithShadow(text, cx - w * 0.5f, y, scale, color, shadowColor);
}

void TextRenderer::drawDialogueBox(const std::string& speaker, const std::string& line1, const std::string& line2,
                                   float x, float y, float w, float h, float scale) {
    Renderer& ren = Renderer::instance();

    // Classic Pokemon Game Boy dialogue frame:
    // Outer border (dark slate)
    ren.drawRect(x - 4, y - 4, w + 8, h + 8, glm::vec4(0.08f, 0.10f, 0.16f, 0.95f));
    // Gold ornamental border
    ren.drawRect(x - 2, y - 2, w + 4, h + 4, glm::vec4(0.85f, 0.70f, 0.20f, 1.0f));
    // Background (parchment cream / dark ninjago indigo)
    ren.drawRect(x, y, w, h, glm::vec4(0.12f, 0.15f, 0.22f, 0.98f));

    // Inner thin border
    ren.drawRectOutline(x + 4, y + 4, w - 8, h - 8, 2.0f, glm::vec4(0.35f, 0.40f, 0.55f, 0.8f));

    // Speaker Name Plate on top
    if (!speaker.empty()) {
        float nameW = getTextWidth(speaker, scale * 0.9f) + 24.0f;
        float nameH = 26.0f;
        float nameX = x + 16.0f;
        float nameY = y + h - 8.0f;

        ren.drawRect(nameX - 2, nameY - 2, nameW + 4, nameH + 4, glm::vec4(0.85f, 0.70f, 0.20f, 1.0f));
        ren.drawRect(nameX, nameY, nameW, nameH, glm::vec4(0.18f, 0.22f, 0.32f, 1.0f));
        drawText(speaker, nameX + 12.0f, nameY + 6.0f, scale * 0.9f, glm::vec4(1.0f, 0.88f, 0.35f, 1.0f));
    }

    // Dialogue Lines
    if (!line1.empty()) {
        drawTextWithShadow(line1, x + 24.0f, y + h - 45.0f, scale, 
                           glm::vec4(0.96f, 0.96f, 1.0f, 1.0f), glm::vec4(0.05f, 0.05f, 0.10f, 1.0f));
    }
    if (!line2.empty()) {
        drawTextWithShadow(line2, x + 24.0f, y + h - 75.0f, scale, 
                           glm::vec4(0.90f, 0.90f, 0.95f, 1.0f), glm::vec4(0.05f, 0.05f, 0.10f, 1.0f));
    }
}

float TextRenderer::getTextWidth(const std::string& text, float scale) const {
    size_t len = 0;
    for (char c : text) {
        if (c != '\n') len++;
    }
    return static_cast<float>(len) * 8.0f * scale;
}

float TextRenderer::getTextHeight(float scale) const {
    return 8.0f * scale;
}
